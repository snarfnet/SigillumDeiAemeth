desc_en = """Mortlake, March 1582. John Dee wrote down what his scryer Edward Kelley saw in a crystal, and drew a seal from it: the Sigillum Dei Aemeth, the Seal of God's Truth.

This app redraws the whole seal from scratch and takes it apart, one layer at a time.

THE SEAL
- All ten layers, from the outer ring of 40 cells to the cross at the centre
- Pick a layer to light it up and read when and how Dee received it
- Tap play to watch the seal build itself in the order Dee received it
- Pinch to zoom into the smallest letters and numbers
- Three looks: wax, manuscript and night

READING THE NAMES
- The ring: start at a capital and count clockwise or counter-clockwise by each number to spell seven names, Thaoth, Galas, Gethog and the rest. Arrows show every count
- The seven angels: the 49 letters shown by seven birds, read down the columns, give Zaphkiel through Gabriel
- The table of names: its rows are the names of God; its diagonals give the Daughters and Sons of Light, and their Daughters and Sons

SOURCES
Letters, numbers and positions come from comparing transcriptions of Dee's record (British Library, Sloane MS 3188) with the manuscript drawing. Where the dictation and the finished drawing disagree, the notes say so.

Japanese and English. No internet connection, no data collected."""

