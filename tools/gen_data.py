#!/usr/bin/env python3
"""Generate App/Data/SealData.swift from tools/data/seal.json and layers_text.json
(research notes on Dee's Sigillum Dei Aemeth, Sloane MS 3188)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "App", "Data", "SealData.swift")


def s(x):
    return json.dumps(x, ensure_ascii=False)


def main():
    seal = json.load(open(os.path.join(HERE, "data", "seal.json"), encoding="utf-8"))
    text = json.load(open(os.path.join(HERE, "data", "layers_text.json"), encoding="utf-8"))
    L = {l["id"]: l for l in seal["layers"]}
    out = ["// Generated by tools/gen_data.py from tools/data/seal.json. Do not edit by hand.", "",
           "extension SealData {"]

    ring = L["L1_outerRing"]
    out.append("    static let ring: [RingCell] = [")
    for c in ring["cells"]:
        pos = {"above": ".above", "below": ".below", None: "nil"}[c["numberPosition"]]
        num = "nil" if c["number"] is None else str(c["number"])
        out.append(f"        RingCell(index: {c['index']}, letter: {s(c['letter'])}, number: {num}, position: {pos}, "
                   f"uncertain: {'true' if c.get('unverified') else 'false'}),")
    out.append("    ]")
    out.append("    static let ringNames: [RingName] = [")
    for d in ring["sevenNames"]["derivations"]:
        out.append(f"        RingName(name: {s(d['name'])}, path: {d['path']}),")
    out.append("    ]")

    sig = L["L2_galethogSigils"]
    out.append("    static let sigils: [Sigil] = [")
    for c in sig["cells"]:
        num = "nil" if c["number"] is None else str(c["number"])
        out.append(f"        Sigil(order: {c['order']}, letter: {s(c['letter'])}, number: {num}, centerDeg: {c['centerDeg']}, ringCell: {c['ringCellItRefersTo']}),")
    out.append("    ]")

    t1 = L["L3_outerHeptagonBand"]
    out.append(f"    static let table1: [String] = {s(t1['table7x7'])}")
    out.append(f"    static let table1Angels: [String] = {s(t1['names'])}")

    g = L["L4_namesOfGod"]
    out.append("    static let table2: [[String]] = [")
    for row in g["table7x7"]:
        out.append(f"        {s(row)},")
    out.append("    ]")
    out.append("    static let godNameTags: [String] = " + s([n["latinTagBesideRow"] for n in g["names"]]))

    h = L["L5_heptagram"]
    out.append("    static let daughters: [String] = " + s([d["name"] for d in h["daughtersOfLight"]]))
    out.append("    static let sons: [String] = " + s([d["name"] for d in h["sonsOfLight"]]))
    out.append("    static let sonStripMidDeg: [Double] = " + s([d["stripMidDeg"] for d in h["sonsOfLight"]]))
    out.append("    static let daughtersOfDaughters: [String] = " + s([d["name"] for d in L["L6_daughtersOfDaughters"]["names"]]))
    out.append("    static let sonsOfSons: [String] = " + s([d["name"] for d in L["L7_sonsOfSons"]["names"]]))
    out.append("    static let table2Angels: [String] = " + s(L["L8_zabathiel"]["angelsOfTable2"]))
    out.append("    static let pentagram: [(capital: String, rest: String)] = ["
               + ", ".join(f"({s(p['capitalInsidePoint'])}, {s(p['restOfNameInNextObtuseAngle'])})" for p in L["L9_pentagram"]["geometry"]["points"]) + "]")

    out.append("    static let layerText: [String: (en: String, ja: String)] = [")
    for k, v in text.items():
        if k.startswith("_"):
            continue
        out.append(f"        {s(k)}: ({s(v['en'])}, {s(v['ja'])}),")
    out.append("    ]")
    out.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("Wrote", OUT)


if __name__ == "__main__":
    main()
